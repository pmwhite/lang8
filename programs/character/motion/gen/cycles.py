# The run cycles the viewer steers from: one stride each at speeds from 1.5 to 10 m/s, as takes
# of 50 frames evenly through the stride (the right foot landing at the first), the root's
# height as the cycle has it and its travel at the cycle's speed.
import sys, math, numpy as np
sys.path.insert(0, '/tmp/chr/gen')
import body as B, synth as S
SPEEDS = [1.5 + 0.5 * k for k in range(18)]
n = 50
out = ["# Run cycles for steering (see README.md): one stride each, generated by gen/cycles.py.", ""]
for v in SPEEDS:
    c = B.cycle(v); T = c['T']; e = c['events']
    out += [f"take cycle_{int(round(v * 10)):03d} run {n / T:.3f}", "  like free", "  hands hand"]
    for k in range(n):
        ph = k / n; s = S.sample(c, ph)
        nums = []
        for key in S.DIRS: nums += list(s[key])
        nums += [0.0, float(s['root_y']), v * T * ph, 0.0]
        downR = ph < e[1]; downL = e[2] <= ph < e[3]
        out.append("  at " + " ".join(f"{x:.4f}" for x in nums) + f" {int(downL)} {int(downR)}")
    out.append("")
open(sys.argv[1], 'w').write("\n".join(out) + "\n")
print(len(SPEEDS), 'cycles')
