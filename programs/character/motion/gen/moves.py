# Maneuver takes for the viewer: each a scripted stick, laid into steps (plan.py), bodied
# (body.py).
import sys, math
sys.path.insert(0, '/tmp/chr/gen')
import plan as P, body as B
from draw import script
MOVES = [
    ('cut_90', [(1.2, 0, 8.0), (2.3, 90, 8.0)], (0, 8.0)),
    ('cut_45', [(1.2, 0, 7.0), (2.0, 45, 7.0)], (0, 7.0)),
    ('cut_60_slow', [(1.2, 0, 4.5), (2.0, -60, 4.5)], (0, 4.5)),
    ('turn_180', [(1.2, 0, 8.0), (3.0, 180, 8.0)], (0, 8.0)),
    ('arc_30', [(1.0, 0, 8.0), (2.5, 30, 8.0)], (0, 8.0)),
    ('stop', [(1.2, 0, 8.0), (2.5, 0, 0.0)], (0, 8.0)),
    ('start', [(0.3, 0, 0.0), (2.5, 0, 9.5)], (0, 0.0)),
]
if __name__ == '__main__':
    out = ["# Maneuvers, laid step by step from the literature's numbers and the change-of-direction",
           "# data of Nitschke et al. 2022 (Zenodo 6949012, CC BY 4.0), bodied from the run cycles",
           "# (see README.md). Generated by gen/moves.py.", ""]
    only = sys.argv[2:]
    for name, parts, v0 in MOVES:
        if only and name not in only: continue
        tr = B.Track(P.plan(script(parts), sum(p[0] for p in parts), v0))
        out += B.take_lines(name, tr) + [""]
        print(name, len(tr.steps), 'steps')
    open(sys.argv[1], 'w').write("\n".join(out) + "\n")
